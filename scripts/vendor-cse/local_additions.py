"""Re-apply Gillian's local additions to a freshly vendored copy of CSE's
OCaml library.

CSE (~/dev/CSE) is the source of truth for the verified encoder.  Gillian needs
three things CSE deliberately does not have, because they are Gillian-specific
and are not part of the verified development:

  * the GIL values `none`, `empty` and `loc`, as constructors of the SMT `Val`
    datatype, together with their type tests and coercions;
  * the matching `Type.t` / `Val.t` constructors in the hand-written wrappers;
  * the `declare-datatype` entries that announce them to the solver.

The first of those is an addition to *extracted* code, so it cannot be a source
edit in CSE and it is not regenerated by extraction.  This script re-applies all
of it after `vendor.sh` has copied CSE over the top.

Each addition is anchored on the corresponding `null` declaration, which is the
sibling of every Gillian value added here and is stable across CSE releases.
An anchor that no longer matches exactly once is a hard error: the tool refuses
to guess.  Re-vendoring is therefore safe to repeat, and never silently
half-applies.

Usage:  local_additions.py [vendored-dir]      (default: ../../GillianCore/cse)
"""

