# Vendored .ml files that reference the utils library.  CSE builds it as `utils`
# (so the module is `Utils`); Gillian must rename it to `extraction_utils` to
# avoid colliding with GillianCore's own `utils`, which wraps it as
# `Extraction_utils.Utils`.  Opening the wrapper restores the `Utils.` prefix
# the copied sources use.
UTILS_OPEN = "open Extraction_utils"


class Failed(Exception):
    pass


def find_unique(lines, anchor, path):
    hits = [i for i, l in enumerate(lines) if l == anchor]
    if len(hits) != 1:
        raise Failed(
            f"{path}: anchor matched {len(hits)} times, expected exactly one\n"
            f"  anchor: {anchor!r}\n"
            f"  CSE's generated code has moved; re-roll this edit by hand."
        )
    return hits[0]


def insertion_point(lines, mode, at, path, anchor):
    if mode == "after_line":
        return at + 1
    if mode == "after_block":
        j = at
        while j < len(lines) and lines[j].strip() != "":
            j += 1
        if j == len(lines):
            raise Failed(f"{path}: no blank line ends the block at {anchor!r}")
        return j + 1
    if mode == "after_arm":
        j = at + 1
        while j < len(lines) and not lines[j].startswith("|"):
            j += 1
        if j == len(lines):
            raise Failed(f"{path}: no following match arm after {anchor!r}")
        return j
    raise Failed(f"unknown mode {mode!r}")


def main(argv):
    root = Path(argv[1]) if len(argv) > 1 else Path(__file__).resolve().parents[2] / "GillianCore" / "cse"
    if not root.is_dir():
        raise Failed(f"no such vendored directory: {root}")

    # Refuse to patch anything twice: vendor.sh always copies clean files first.
    for rel in sorted({e[0] for e in EDITS}):
        text = (root / rel).read_text()
        if MARKER in text.lower():
            raise Failed(
                f"{rel} already contains Gillian additions.\n"
                f"  Run vendor.sh, which copies clean files from CSE first."
            )

    by_file = {}
    for rel, mode, anchor, note, payload in EDITS:
        by_file.setdefault(rel, []).append((mode, anchor, note, payload))

    for rel, edits in by_file.items():
        path = root / rel
        lines = path.read_text().split("\n")
        # Apply bottom-up so earlier insertions cannot shift later anchors.
        located = []
        for mode, anchor, note, payload in edits:
            at = find_unique(lines, anchor, rel)
            located.append((insertion_point(lines, mode, at, rel, anchor), payload, note))
        for point, payload, _note in sorted(located, key=lambda x: -x[0]):
            lines[point:point] = payload.split("\n")
        path.write_text("\n".join(lines))
        print(f"  {rel}: {len(edits)} additions")

    # The utils library rename.
    for path in sorted(root.rglob("*.ml")):
        text = path.read_text()
        if "Utils." in text and UTILS_OPEN not in text:
            path.write_text(UTILS_OPEN + "\n\n" + text)
            print(f"  {path.relative_to(root)}: + {UTILS_OPEN}")

    # Post-conditions.
    problems = []
    for rel, names in EXPECTED.items():
        text = (root / rel).read_text()
        missing = [n for n in names if n not in text]
        if missing:
            problems.append(f"{rel}: missing {', '.join(missing)}")
    if problems:
        raise Failed("additions did not land:\n  " + "\n  ".join(problems))

    print(f"applied {len(EDITS)} additions across {len(by_file)} files; all post-conditions hold")


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv) or 0)
    except Failed as e:
        print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
